const DOMAIN_ORDER = Object.keys(RULES) as Domain[];

export function classify(repo: { description: string | null; topics: string[]; language: string | null }): Domain {
  const text = ` ${(repo.description ?? "").toLowerCase()} `;
  const topics = new Set(repo.topics.map((t) => t.toLowerCase()));
  let best: Domain = "devtools";
  let bestScore = 0;
  for (const domain of DOMAIN_ORDER) {
    const rule = RULES[domain];
    let score = 0;
    for (const topic of rule.topics) if (topics.has(topic)) score += 3;
    for (const word of rule.words) if (text.includes(word)) score += 1;
    if (repo.language && rule.languages?.includes(repo.language)) score += 1;
    if (score > bestScore) {
      best = domain;
      bestScore = score;
    }
  }
  return best;
}
